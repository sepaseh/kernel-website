"""Verify committed website fonts in CI; regenerate them only when explicitly requested."""

import argparse
import hashlib
import io
import json
from pathlib import Path

import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parent.parent
WEBSITE = ROOT / "."
SOURCE = WEBSITE / "font-source/vazirmatn-variable.woff2"
FONT_DIR = WEBSITE / "public/fonts"
GENERATED = WEBSITE / "src/shared/fonts"


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ", ".join(
        f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}"
        for start, end in groups
    )


def digest(data):
    return hashlib.sha256(data).hexdigest()


def is_arabic(point):
    return (
        0x0600 <= point <= 0x08FF
        or 0xFB50 <= point <= 0xFDFF
        or 0xFE70 <= point <= 0xFEFF
        or 0x1EE00 <= point <= 0x1EEFF
        or 0x200C <= point <= 0x200F
        or 0x202A <= point <= 0x202E
    )


def is_latin(point):
    return (
        point <= 0xFF
        # Keep all letters used by our registered Latin-script languages in
        # one face, including Turkish and French Y-diaeresis. Splitting a word
        # between unicode-range faces loses cross-character kerning.
        or point in {0x011E, 0x011F, 0x0130, 0x0131, 0x0152, 0x0153,
                     0x015E, 0x015F, 0x0178, 0x02BB, 0x02BC, 0x02C6, 0x02DA,
                     0x02DC, 0x0304, 0x0308, 0x0329, 0x2113, 0xFFFD}
        or 0x2000 <= point <= 0x206F
        or 0x20A0 <= point <= 0x20C0
    )


def generate():
    original = SOURCE.read_bytes()
    source = TTFont(io.BytesIO(original), recalcTimestamp=False)
    codepoints = set(source.getBestCmap())
    arabic = {point for point in codepoints if is_arabic(point)}
    latin = {point for point in codepoints - arabic if is_latin(point)}
    partitions = {"latin": latin, "arabic": arabic,
                  "extended": codepoints - latin - arabic}
    if (set.union(*partitions.values()) != codepoints
            or sum(map(len, partitions.values())) != len(codepoints)):
        raise ValueError("Font partitions must cover the source without overlapping assignments.")
    axes = {axis.axisTag: [axis.minValue, axis.defaultValue, axis.maxValue]
            for axis in source["fvar"].axes}
    standard_features = subset.Options().layout_features
    source_features = {record.FeatureTag for tag in ("GSUB", "GPOS")
                       if tag in source and source[tag].table.FeatureList
                       for record in source[tag].table.FeatureList.FeatureRecord}
    metadata = {"version": 1, "source": {
        "path": "font-source/vazirmatn-variable.woff2",
        "sha256": digest(original), "bytes": len(original),
        "version": source["name"].getDebugName(5),
        "codepointCount": len(codepoints), "axes": axes,
    }, "tools": {"fonttools": fontTools.__version__, "brotli": brotli.__version__},
        "layout": {"policy": "fonttools-standard",
                   "excludedOptionalFeatures": sorted(source_features - set(standard_features))},
        "subsets": {}}
    outputs = {}
    css = ["/* Generated by scripts/subset-website-fonts.py; see docs/fonts.md. */"]
    for name, assigned in partitions.items():
        font = TTFont(io.BytesIO(original), recalcTimestamp=False)
        options = subset.Options()
        # Keep standard shaping, joining, kerning and ligatures. The website
        # does not use optional small caps, stylistic sets or tabular digits;
        # enabling those later requires regenerating from the full source.
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        # Supporting spaces remain available for shaping. CSS assignments stay
        # disjoint so a Latin space never triggers another alphabet download.
        support = {0x20, 0xA0} & codepoints
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=assigned | support)
        subsetter.subset(font)
        if not assigned <= set(font.getBestCmap()):
            raise ValueError("A font subset lost assigned source codepoints.")
        if {axis.axisTag: [axis.minValue, axis.defaultValue, axis.maxValue]
                for axis in font["fvar"].axes} != axes:
            raise ValueError("A font subset changed the source weight axes.")
        for name_id in (0, 13, 14):
            if font["name"].getDebugName(name_id) != source["name"].getDebugName(name_id):
                raise ValueError("A font subset changed source copyright or license metadata.")
        data = io.BytesIO()
        font.flavor = "woff2"
        font.save(data)
        value = data.getvalue()
        filename = f"vazirmatn-{name}.woff2"
        outputs[FONT_DIR / filename] = value
        unicode_range = ranges(assigned)
        metadata["subsets"][name] = {
            "href": f"/fonts/{filename}", "sha256": digest(value),
            "bytes": len(value), "codepointCount": len(assigned),
            "unicodeRange": unicode_range,
        }
        css.append(f'''@font-face {{
  font-family: "Vazirmatn";
  src: url("/fonts/{filename}") format("woff2");
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  unicode-range: {unicode_range};
}}''')
    outputs[GENERATED / "vazirmatn.css"] = ("\n".join(css) + "\n").encode()
    outputs[GENERATED / "manifest.json"] = (json.dumps(metadata, ensure_ascii=False, indent=2) + "\n").encode()
    return outputs


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated assets without writing")
    args = parser.parse_args()
    for target, content in generate().items():
        if args.check:
            if not target.is_file() or target.read_bytes() != content:
                raise SystemExit(f"Stale font asset: {target.relative_to(ROOT)}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        print(f"{target.relative_to(ROOT)}: {len(content):,} bytes")
